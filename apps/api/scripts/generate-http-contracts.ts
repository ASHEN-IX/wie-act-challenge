import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { format, resolveConfig } from 'prettier';
import { loadDefinitions } from '../src/domain-definitions';
import { publicRoutePath } from '../src/framework/route-path';

// Generated adapters bind named operation keys rather than mutable array offsets.
// Run after changing domain routes. Business logic stays in named domain handlers.
async function generateContracts(): Promise<void> {
  const outputDirectory = path.resolve(__dirname, '../src/framework/domains');
  for (const definition of loadDefinitions()) {
    const title = definition.name[0].toUpperCase() + definition.name.slice(1);
    const decorators = [
      ...new Set(definition.operations.map((op) => op.method[0].toUpperCase() + op.method.slice(1)))
    ];
    const methods = definition.operations
      .map((op) => {
        const verb = op.method[0].toUpperCase() + op.method.slice(1);
        const key = `${op.method.toUpperCase()} ${op.path}`;
        const suffix = crypto.createHash('sha256').update(key).digest('hex').slice(0, 8);
        const method = `${op.method}${op.path
          .split('/')
          .filter((part) => !part.startsWith(':'))
          .map((part) => part.replace(/[^a-z\d]/gi, ''))
          .join('_')}_${suffix}`;
        return `  @${verb}(${JSON.stringify(publicRoutePath(op.path))})\n  ${method}(@Req() req: DomainRequest, @Res() res: Response): Promise<void> {\n    return this.service.execute(${JSON.stringify(key)}, req, res);\n  }`;
      })
      .join('\n');
    const source = `// Generated by scripts/generate-http-contracts.ts.\nimport { Controller, Module, Injectable, Inject, Req, Res, UseGuards, ${decorators.join(', ')} } from '@nestjs/common';\nimport type { Response } from 'express';\nimport type { DomainRequest } from '../contracts';\nimport { DomainService } from '../domain.service';\nimport { SessionGuard } from '../auth.guard';\nconst definitions = require('../../domain-definitions').loadDefinitions();\n@Injectable()\nexport class ${title}Service extends DomainService {\n  constructor() { super(definitions.find((entry: { name: string }) => entry.name === '${definition.name}')); }\n}\n@Controller()\n@UseGuards(SessionGuard)\nexport class ${title}Controller {\n  constructor(@Inject(${title}Service) private readonly service: ${title}Service) {}\n${methods}\n}\n@Module({ controllers: [${title}Controller], providers: [${title}Service, SessionGuard], exports: [${title}Service] })\nexport class ${title}Module {}\n`;
    const filename = path.join(outputDirectory, `${definition.name}.module.ts`);
    const options = await resolveConfig(filename);
    fs.writeFileSync(filename, await format(source, { ...options, filepath: filename }));
  }
}

void generateContracts().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
