const { test, expect } = require('@playwright/test');
const email = process.env.AUTH_E2E_TEST_EMAIL || `browser-${Date.now()}@example.test`;
const password = 'BrowserPass!123';
test('Next.js and NestJS: register, verify email, login, persist session, logout', async ({ page, request }) => {
  await page.goto('/dashboard');
  await expect(page).toHaveURL(/\/login/);
  const registration = await request.post('/api/auth/sign-up/email', {
    headers: { origin: process.env.E2E_BASE_URL || process.env.AUTH_E2E_ORIGIN || 'http://localhost:5173' }, data: { name: 'Browser Test', email, password, callbackURL: '/verify-email?verified=true' }
  });
  expect(registration.status()).toBe(200);
  const messages = await (await request.get(`${process.env.AUTH_TEST_MAIL_URL || 'http://127.0.0.1:8026'}/api/v1/messages`)).json();
  const summary = messages.messages.find(message => message.To.some(recipient => recipient.Address === email));
  expect(summary).toBeTruthy();
  const mail = await (await request.get(`${process.env.AUTH_TEST_MAIL_URL || 'http://127.0.0.1:8026'}/api/v1/message/${summary.ID}`)).json();
  const link = mail.Text.match(/https?:\/\/\S+/)[0];
  await page.goto(link);
  await expect(page).toHaveURL(/verified=true/);
  await page.goto('/login');
  await page.locator('input[name="email"]').fill(email);
  await page.locator('input[name="password"]').fill(password);
  await page.locator('button[type="submit"]').click();
  await expect(page).toHaveURL(/\/dashboard/, { timeout: 20000 });
  await expect(page.getByText('Loading session…')).toHaveCount(0);
  await page.reload();
  await expect(page).toHaveURL(/\/dashboard/);
  const cookies = await page.context().cookies();
  expect(cookies.some(cookie => cookie.name.includes('session_token') && cookie.httpOnly)).toBe(true);
  const storage = await page.evaluate(() => JSON.stringify(localStorage));
  expect(storage).not.toContain('session_token');
  const authenticated = await page.request.get('/api/v1/auth/me');
  expect(authenticated.status()).toBe(200);
  expect((await page.request.get('/api/v1/auth/admin/stats')).status()).toBe(403);
  const oldCookie = cookies.map(cookie => `${cookie.name}=${cookie.value}`).join('; ');
  expect((await page.request.post('/api/auth/sign-out', { data: {}, headers: { origin: process.env.E2E_BASE_URL || process.env.AUTH_E2E_ORIGIN || 'http://localhost:5173' } })).status()).toBe(200);
  expect((await request.get('/api/v1/auth/me', { headers: { cookie: oldCookie } })).status()).toBe(401);
  await page.goto('/dashboard');
  await expect(page).toHaveURL(/\/login/);
});
test('password reset uses the delivered link and invalidates the previous session', async ({ page, request }) => {
  const origin = process.env.E2E_BASE_URL || process.env.AUTH_E2E_ORIGIN || 'http://localhost:5173';
  const login = await page.request.post('/api/auth/sign-in/email', { headers: { origin }, data: { email, password } });
  expect(login.status()).toBe(200);
  const oldCookie = (await page.context().cookies()).map(cookie => `${cookie.name}=${cookie.value}`).join('; ');
  const reset = await request.post('/api/auth/request-password-reset', { headers: { origin }, data: { email, redirectTo: '/reset-password' } });
  expect(reset.status()).toBe(200);
  const mailBase = process.env.AUTH_TEST_MAIL_URL || 'http://127.0.0.1:8026';
  const messages = await (await request.get(`${mailBase}/api/v1/messages`)).json();
  const summary = messages.messages.find(message => /reset/i.test(message.Subject) && message.To.some(recipient => recipient.Address === email));
  expect(summary).toBeTruthy();
  const mail = await (await request.get(`${mailBase}/api/v1/message/${summary.ID}`)).json();
  await page.goto(mail.Text.match(/https?:\/\/\S+/)[0]);
  await page.locator('input[type="password"]').nth(0).fill('ChangedBrowserPass!456');
  await page.locator('input[type="password"]').nth(1).fill('ChangedBrowserPass!456');
  await page.locator('button[type="submit"]').click();
  await expect(page.getByText('Password Reset!')).toBeVisible();
  expect((await request.get('/api/v1/auth/me', { headers: { cookie: oldCookie } })).status()).toBe(401);
  await page.goto('/login');
  await page.locator('input[name="email"]').fill(email);
  await page.locator('input[name="password"]').fill('ChangedBrowserPass!456');
  await page.locator('button[type="submit"]').click();
  await expect(page).toHaveURL(/\/dashboard/);
  await page.request.post('/api/auth/sign-out', { data: {}, headers: { origin } });
});
