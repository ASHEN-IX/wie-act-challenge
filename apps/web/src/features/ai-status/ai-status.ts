/**
 * Plain-language AI status for learners. Maps the API's execution mode to what the
 * learner should understand, and times the staged progress shown during long waits.
 */

export type AiExecutionMode =
  | "REAL_APPROVED"
  | "MOCK_TEST"
  | "DETERMINISTIC_FALLBACK"
  | "UNAVAILABLE";

export interface AiModeNote {
  tone: "ok" | "notice" | "warning";
  title: string;
  detail: string;
}

const NOTES: Record<AiExecutionMode, AiModeNote> = {
  REAL_APPROVED: {
    tone: "ok",
    title: "Answered by the AI model",
    detail: "Generated by an approved AI model.",
  },
  MOCK_TEST: {
    tone: "notice",
    title: "Test answer",
    detail: "This environment is not connected to a real AI model.",
  },
  DETERMINISTIC_FALLBACK: {
    tone: "notice",
    title: "Built-in guidance",
    detail:
      "This answer follows fixed rules rather than an AI model. When a model is available again, you can ask for a model-generated answer.",
  },
  UNAVAILABLE: {
    tone: "warning",
    title: "AI unavailable",
    detail: "No answer could be generated right now. Try again in a moment.",
  },
};

export function describeAiMode(mode: string | null | undefined): AiModeNote {
  if (mode && mode in NOTES) return NOTES[mode as AiExecutionMode];
  return NOTES.UNAVAILABLE;
}

export const AI_WAIT_STAGES = [
  "Reading your sources",
  "Preparing an answer",
  "Waiting for the AI model",
  "Still working. Longer answers can take a little while.",
] as const;

export const AI_WAIT_STAGE_MS = 4000;

/** Stage shown after `elapsedMs`; advances every AI_WAIT_STAGE_MS and stops at the last stage. */
export function waitStageIndex(
  elapsedMs: number,
  stageMs: number = AI_WAIT_STAGE_MS,
  stageCount: number = AI_WAIT_STAGES.length,
): number {
  const step = Math.floor(Math.max(0, elapsedMs) / stageMs);
  return Math.min(stageCount - 1, step);
}
