/**
 * Learner-facing wording for the AI execution mode reported by the backend.
 *
 * The API reports a machine enum (REAL_APPROVED / MOCK_TEST /
 * DETERMINISTIC_FALLBACK / UNAVAILABLE). Rendering that raw token next to an
 * answer tells a learner nothing and, worse, hides when an answer came from a
 * deterministic fallback rather than inference. These labels say what produced
 * the text and whether to trust it as model output.
 */
export type ExecutionMode =
  | "REAL_APPROVED"
  | "MOCK_TEST"
  | "DETERMINISTIC_FALLBACK"
  | "UNAVAILABLE";

export interface ExecutionNotice {
  mode: ExecutionMode | null;
  label: string;
  description: string;
  /** True when the content is generated by a model rather than derived rules. */
  isModelOutput: boolean;
  tone: "neutral" | "caution";
}

export function describeExecutionMode(raw?: string | null): ExecutionNotice {
  switch (raw) {
    case "REAL_APPROVED":
      return {
        mode: "REAL_APPROVED",
        label: "Model answer",
        description: "Generated by the approved model from your course sources.",
        isModelOutput: true,
        tone: "neutral",
      };
    case "MOCK_TEST":
      return {
        mode: "MOCK_TEST",
        label: "Test mode",
        description:
          "Produced by a test double, not the live model. Do not treat it as course content.",
        isModelOutput: false,
        tone: "caution",
      };
    case "DETERMINISTIC_FALLBACK":
      return {
        mode: "DETERMINISTIC_FALLBACK",
        label: "Rule-based answer",
        description:
          "Inference was unavailable, so this came from reviewed course rules and sources rather than a model.",
        isModelOutput: false,
        tone: "caution",
      };
    case "UNAVAILABLE":
      return {
        mode: "UNAVAILABLE",
        label: "Unavailable",
        description: "No grounded answer could be produced for this request right now.",
        isModelOutput: false,
        tone: "caution",
      };
    default:
      return {
        mode: null,
        label: "Status unknown",
        description: "The service did not report how this answer was produced.",
        isModelOutput: false,
        tone: "caution",
      };
  }
}
